package DAY_2;

public class Switch_Case {

	public static void main(String[] args) {
		String color="red";
		switch(color) {
		case "red":
			System.out.println("Holi");
			break;
		case "yellow":
			System.out.println("Dasara");
			break;
		case "green":
			System.out.println("Something");
			break;
		}	
	}
}
